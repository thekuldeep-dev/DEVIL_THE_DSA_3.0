public class Type_Casting{
    public static void main(String[] args){
        float f = 45.2f;
        int a = (int) f;
        System.out.println(a);

        //Type casting(narrow/explicit)

        char ch = 'a';
        int num = (int) ch;
        System.out.println(num);
    }      
}        
    
    

