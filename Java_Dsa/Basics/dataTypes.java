public class dataTypes {
    public static void main(String args[]){
        byte b = 8;
        System.out.println(b);

        char ch = 'a';
        System.out.println(ch);

        boolean bool = true;
        System.out.println(bool);

        float f = 10.5f;
        System.out.println(f);
        
        int s = 56;
        System.out.println(s);

        // long
        //double

        short sh = 54;
        System.out.println(sh);

        /*
            Size of dataType:-
                                char  - 2 bytes
                                short - 2 bytes
                                byte  - 1 bytes
                                int   - 4 bytes
                                boolean - 1 bytes
                                float - 4 bytes
                                double - 8 bytes
                                long  - 8 bytes

        */
    }
}
